package project

import (
	"bytes"
	"embed"
	"fmt"
	"os"
	"path/filepath"
	"text/template"

	"devforge/internal/config"
)

//go:embed templates/*
var templates embed.FS

type composeData struct{ Go, Java, Python, Redis bool }

func Generate(dir string, cfg config.Config, force bool) (int, error) {
	dirs := []string{"services/go/cmd/app", "services/java/src/main/java/devforge", "services/java/src/main/resources",
		"services/java/src/test/java/devforge", "services/python/app", "services/python/tests",
		"reports/junit", "reports/coverage", "reports/security", "reports/html"}
	for _, d := range dirs {
		if e := os.MkdirAll(filepath.Join(dir, d), 0755); e != nil {
			return 0, e
		}
	}
	data := composeData{cfg.Stacks.Go, cfg.Stacks.Java, cfg.Stacks.Python, cfg.Stacks.Redis}
	count := 0
	render := func(src, dst string, v any) error {
		b, e := templates.ReadFile(src)
		if e != nil {
			return e
		}
		t, e := template.New(src).Parse(string(b))
		if e != nil {
			return e
		}
		var out bytes.Buffer
		if e = t.Execute(&out, v); e != nil {
			return e
		}
		n, e := writeFile(dir, dst, out.Bytes(), force)
		if n {
			count++
		}
		return e
	}
	copy := func(src, dst string) error {
		b, e := templates.ReadFile(src)
		if e != nil {
			return e
		}
		n, e := writeFile(dir, dst, b, force)
		if n {
			count++
		}
		return e
	}
	if e := render("templates/compose.yaml.tmpl", "compose.yaml", data); e != nil {
		return count, e
	}
	files := map[string]string{
		"templates/go.Dockerfile":          "services/go/Dockerfile",
		"templates/air.toml":               "services/go/.air.toml",
		"templates/go-main.go":             "services/go/cmd/app/main.go",
		"templates/go.mod.tmpl":            "services/go/go.mod",
		"templates/java.Dockerfile":        "services/java/Dockerfile",
		"templates/pom.xml":                "services/java/pom.xml",
		"templates/java-main.java":         "services/java/src/main/java/devforge/DevForgeApplication.java",
		"templates/java-health.java":       "services/java/src/main/java/devforge/HealthController.java",
		"templates/java-test.java":         "services/java/src/test/java/devforge/HealthControllerTest.java",
		"templates/application.properties": "services/java/src/main/resources/application.properties",
		"templates/python.Dockerfile":      "services/python/Dockerfile",
		"templates/requirements.txt":       "services/python/requirements.txt",
		"templates/python-main.py":         "services/python/app/main.py",
		"templates/python-test.py":         "services/python/tests/test_health.py",
		"templates/gitignore":              ".gitignore",
	}
	for src, dst := range files {
		if e := copy(src, dst); e != nil {
			return count, fmt.Errorf("%s: %w", dst, e)
		}
	}
	readme := []byte("# " + cfg.Name + "\n\nGenerated by DevForge. See `devforge.yaml`.\n\nCommands: `devforge up`, `devforge watch`, `devforge test`, `devforge security`, `devforge report`, `devforge down`.\n")
	n, e := writeFile(dir, "README.md", readme, force)
	if n {
		count++
	}
	return count, e
}
func writeFile(dir, rel string, b []byte, force bool) (bool, error) {
	p := filepath.Join(dir, rel)
	if _, e := os.Stat(p); e == nil && !force {
		return false, nil
	}
	if e := os.MkdirAll(filepath.Dir(p), 0755); e != nil {
		return false, e
	}
	if e := os.WriteFile(p, b, 0644); e != nil {
		return false, e
	}
	return true, nil
}
